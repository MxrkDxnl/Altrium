export default function SummaryCards({ cards = [] }) {
  if (!cards || cards.length === 0) return null;

  return (
    <div className="grid grid-cols-1 sm:grid-cols-2 xl:grid-cols-4 gap-4 sm:gap-5 w-full">
      {cards.map((card) => {
        const isGold = card.highlight === 'gold';
        return (
          <div
            key={card.id || card.title}
            className={`bg-white rounded-xl p-4 sm:p-5 border transition-all duration-200 shadow-sm hover:shadow-md flex flex-col justify-between ${
              isGold ? 'border-amber-200/80 bg-gradient-to-br from-white to-amber-50/20' : 'border-gray-200'
            }`}
          >
            <div>
              <div className="flex items-start justify-between gap-3">
                <div className="min-w-0 flex-1">
                  <p className="text-xs font-bold uppercase tracking-wider text-gray-700 break-words leading-snug">
                    {card.title}
                  </p>
                  <p className="text-2xl sm:text-3xl font-extrabold text-gray-900 mt-2 tracking-tight">
                    {card.value}
                  </p>
                </div>
                <div className="p-2 sm:p-2.5 rounded-lg bg-gray-50 border border-gray-100 flex-shrink-0">
                  {renderIcon(card.icon)}
                </div>
              </div>
            </div>
            {card.subtitle && (
              <p className="text-xs text-gray-700 mt-3 pt-2.5 border-t border-gray-100 font-medium break-words leading-snug">
                {card.subtitle}
              </p>
            )}
          </div>
        );
      })}
    </div>
  );
}
